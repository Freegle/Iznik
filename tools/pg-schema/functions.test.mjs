// Checks the PostgreSQL stored functions (iznik-batch/database/postgres/functions.sql) against the
// answers MySQL gave for the same inputs (iznik-batch/tests/fixtures/stored-functions/cases.json).
// Needs a PostgreSQL server with PostGIS; skipped unless PG_SCHEMA_PSQL says how to reach one.
//
//   PG_SCHEMA_PSQL="docker exec -i freegle-postgres psql -U root" node --test tools/pg-schema/functions.test.mjs
//
// The value is a psql command line without -d. The test creates a database named
// ${PG_FUNCTIONS_DB:-pg_functions_test}, drops it afterwards, and touches nothing else. The same table
// is run on MySQL by iznik-batch/tests/Feature/Database/StoredFunctionsTest.php.
import test, { before, after } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const PSQL = process.env.PG_SCHEMA_PSQL
const DB = process.env.PG_FUNCTIONS_DB || 'pg_functions_test'
const functionsPath = path.join(here, '../../iznik-batch/database/postgres/functions.sql')
const casesPath = path.join(here, '../../iznik-batch/tests/fixtures/stored-functions/cases.json')
const migrationPath = path.join(here, '../../iznik-batch/database/migrations/2026_02_20_000002_create_stored_functions.php')
const skip = PSQL ? false : 'PG_SCHEMA_PSQL is not set'

const cases = JSON.parse(fs.readFileSync(casesPath, 'utf8'))

function psql(db, sql, opts = {}) {
  const r = spawnSync('sh', ['-c', `${PSQL} -d ${db} -X -q -At -F '\t' -v ON_ERROR_STOP=1`], { input: sql, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  if (opts.allowError) return r
  assert.equal(r.status, 0, `psql failed: ${r.stderr}`)
  return r.stdout
}

// One result row per input, in order, so a whole table is one round trip.
function column(sql) {
  return psql(DB, sql).replace(/\n$/, '').split('\n')
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`
const numOrNull = (v) => (v === null || v === undefined ? 'NULL' : String(v))
const parse = (s) => (s === '' || s === undefined ? null : Number(s))
const rel = (a, b) => Math.abs(a - b) / Math.max(Math.abs(a), Math.abs(b), Number.MIN_VALUE)

before(() => {
  if (skip) return
  psql('postgres', `DROP DATABASE IF EXISTS ${DB} WITH (FORCE); CREATE DATABASE ${DB};`)
  psql(DB, fs.readFileSync(functionsPath, 'utf8'))
  psql(
    DB,
    `CREATE EXTENSION IF NOT EXISTS citext;
     CREATE TABLE domains_common (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain citext NOT NULL, count integer NOT NULL);
     INSERT INTO domains_common (domain, count) VALUES ${cases.domains.map((d) => `(${lit(d.domain)}, ${d.count})`).join(', ')};`,
  )
})

after(() => {
  if (skip) return
  psql('postgres', `DROP DATABASE IF EXISTS ${DB} WITH (FORCE);`)
})

test('the file loads again over a database that already has the functions', { skip }, () => {
  psql(DB, fs.readFileSync(functionsPath, 'utf8'))
})

