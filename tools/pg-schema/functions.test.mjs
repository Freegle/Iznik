test('haversine gives the answer MySQL gave, NULL where MySQL gave NULL', { skip }, () => {
  const sql = cases.haversine
    .map((c) => `SELECT haversine(${c.args.map(numOrNull).join(', ')})::float8;`)
    .join('\n')
  const out = column(sql)
  assert.equal(out.length, cases.haversine.length)
  let worst = 0
  const bad = []
  cases.haversine.forEach((c, i) => {
    const got = parse(out[i])
    const want = c.mysql
    if (want === null || got === null) {
      if (want !== got) bad.push(`${c.name}: MySQL ${want}, PostgreSQL ${got}`)
      return
    }
    const d = rel(got, want)
    worst = Math.max(worst, d)
    if (d > 1e-6) bad.push(`${c.name}: MySQL ${want}, PostgreSQL ${got}`)
  })
  assert.deepEqual(bad, [])
  console.log(`# haversine: ${cases.haversine.length} inputs, largest relative difference ${worst.toExponential(2)}`)
})

test('haversine is NULL for the same point where MySQL is, and the table holds both kinds', { skip }, () => {
  const same = cases.haversine.filter((c) => c.name.startsWith('same point'))
  assert.ok(same.filter((c) => c.mysql === null).length >= 10)
  assert.ok(same.filter((c) => c.mysql !== null).length >= 10)
})

test('haversine takes a numeric column, a real column and bare literals, and a NULL argument gives NULL', { skip }, () => {
  const out = psql(
    DB,
    `CREATE TEMP TABLE pts (lat numeric(10,6), lng numeric(10,6), rlat real, rlng real);
     INSERT INTO pts VALUES (51.5074, -0.1278, 51.5074, -0.1278);
     SELECT haversine(lat, lng, 53.4808, -2.2426)::float8, haversine(rlat, rlng, 53.4808, -2.2426)::float8, haversine(51.5074, -0.1278, 53.4808, -2.2426)::float8, haversine(NULL, 0, 0, 0) IS NULL FROM pts;`,
  ).trim().split('\t')
  const want = cases.haversine.find((c) => c.name === 'london to manchester').mysql
  assert.ok(rel(Number(out[0]), want) < 1e-6)
  assert.ok(rel(Number(out[1]), want) < 1e-6)
  assert.ok(rel(Number(out[2]), want) < 1e-6)
  assert.equal(out[3], 't')
})

test('haversine is a real, as the MySQL function returns FLOAT', { skip }, () => {
  assert.equal(psql(DB, `SELECT pg_typeof(haversine(1, 2, 3, 4))`).trim(), 'real')
})

// ------------------------------------------------------------------------------------------
// haversine_miles and the reconciliation of the distance definitions
// ------------------------------------------------------------------------------------------

// The form the PHP and Go code use for miles: atan2 on the half-angle terms, 3959 mile earth.
function phpMiles(lat1, lng1, lat2, lng2) {
  const rad = (d) => (d * Math.PI) / 180
  const dLat = rad(lat2 - lat1)
  const dLng = rad(lng2 - lng1)
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(rad(lat1)) * Math.cos(rad(lat2)) * Math.sin(dLng / 2) ** 2
  return 3959 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
}

test('haversine_miles agrees with the PHP and Go form of the same distance', { skip }, () => {
  const pairs = cases.haversine.filter((c) => c.args.every((v) => v !== null))
  const out = column(pairs.map((c) => `SELECT haversine_miles(${c.args.join(', ')});`).join('\n'))
  let worst = 0
  pairs.forEach((c, i) => {
    const got = Number(out[i])
    const want = phpMiles(...c.args)
    // acos loses precision for very short distances, so compare in absolute terms there.
    const d = Math.abs(got - want)
    worst = Math.max(worst, d)
    assert.ok(d < 1e-3 || rel(got, want) < 1e-9, `${c.name}: PostgreSQL ${got}, PHP form ${want}`)
  })
  console.log(`# haversine_miles: ${pairs.length} pairs, largest absolute difference ${worst.toExponential(2)} miles`)
})

test('haversine_miles never gives NULL or an error for the same point or for antipodes', { skip }, () => {
  const out = column(
    `SELECT haversine_miles(lat, lng, lat, lng) FROM (VALUES ${cases.haversine
      .filter((c) => c.name.startsWith('same point'))
      .map((c) => `(${c.args[0]}::float8, ${c.args[1]}::float8)`)
      .join(', ')}) AS t(lat, lng);
     SELECT haversine_miles(0, 0, 0, 180), haversine_miles(90, 0, -90, 0);`,
  )
  const same = out.slice(0, -1)
  assert.ok(same.length >= 20)
  for (const v of same) assert.ok(Number(v) < 1e-3, `same point gave ${v}`)
  const [a, b] = out[out.length - 1].split('\t').map(Number)
  assert.ok(Math.abs(a - Math.PI * 3959) < 1e-6)
  assert.ok(Math.abs(b - Math.PI * 3959) < 1e-6)
})

test('haversine is the 3959 mile distance scaled by 69 miles to the degree, as every caller assumes', { skip }, () => {
  // 69 miles per degree against 3959 * pi / 180 = 69.0934 miles per degree. The arguments are single
  // precision, which moves a short distance by more than the tolerance, so only long ones are compared.
  const k = 69 / ((3959 * Math.PI) / 180)
  const far = cases.haversine.filter((c) => c.args.every((v) => v !== null) && phpMiles(...c.args) > 100 && !/past the/.test(c.name))
  const out = column(far.map((c) => `SELECT haversine(${c.args.join(', ')})::float8 / haversine_miles(${c.args.join(', ')});`).join('\n'))
  far.forEach((c, i) => {
    const got = Number(out[i])
    assert.ok(Math.abs(got - k) < 2e-5, `${c.name}: ratio ${got}, expected ${k}`)
  })
  assert.ok(k > 0.9985 && k < 0.9986)
})

