const geom = (wkt) => `ST_GeomFromText(${lit(wkt)}, 4326)`

test('GetMaxDimension gives the answer MySQL gave', { skip }, () => {
  const ok = cases.maxdimension.filter((c) => !c.mysqlError)
  const out = column(ok.map((c) => `SELECT GetMaxDimension(${geom(c.wkt)});`).join('\n'))
  assert.equal(out.length, ok.length)
  let worst = 0
  ok.forEach((c, i) => {
    const got = Number(out[i])
    if (c.mysql === 0) {
      assert.equal(got, 0, c.name)
      return
    }
    const d = rel(got, c.mysql)
    worst = Math.max(worst, d)
    assert.ok(d < 1e-12, `${c.name}: MySQL ${c.mysql}, PostgreSQL ${got}`)
  })
  console.log(`# GetMaxDimension: ${ok.length} geometries, largest relative difference ${worst.toExponential(2)}`)
})

test('where MySQL refuses a geometry, PostgreSQL answers as the divergence block says', { skip }, () => {
  const refused = cases.maxdimension.filter((c) => c.mysqlError)
  assert.ok(refused.length >= 1)
  for (const c of refused) {
    assert.ok(c.divergence, `${c.name} needs a divergence block`)
    const got = Number(column(`SELECT GetMaxDimension(${geom(c.wkt)});`)[0])
    assert.ok(rel(got, c.divergence.pg) < 1e-12, `${c.name}: expected ${c.divergence.pg}, got ${got}`)
  }
})

test('GetMaxDimension of NULL is 0, not NULL, as in MySQL', { skip }, () => {
  assert.equal(column(`SELECT GetMaxDimension(NULL)`)[0], '0')
})

test('GetMaxDimensionT is the same function', { skip }, () => {
  for (const c of cases.maxdimension.filter((x) => !x.mysqlError)) {
    const [a, b] = column(`SELECT GetMaxDimension(${geom(c.wkt)}), GetMaxDimensionT(${geom(c.wkt)});`)[0].split('\t')
    assert.equal(a, b, c.name)
  }
})

test('GetMaxDimension works on a stored geometry column the way the location code calls it', { skip }, () => {
  const out = psql(
    DB,
    `CREATE TEMP TABLE locs (id int, geometry geometry(Geometry, 4326), maxdimension numeric(10,6));
     INSERT INTO locs SELECT i, ST_GeomFromText('POLYGON((0 0,0 10,10 10,10 0,0 0))', 4326), NULL FROM generate_series(1, 3) i;
     INSERT INTO locs VALUES (4, ST_GeomFromText('POINT(1 1)', 4326), NULL);
     UPDATE locs SET maxdimension = GetMaxDimension(geometry);
     SELECT id, maxdimension FROM locs ORDER BY id;`,
  ).trim().split('\n').map((l) => l.split('\t'))
  assert.deepEqual(out, [['1', '7.978846'], ['2', '7.978846'], ['3', '7.978846'], ['4', '0.000000']])
})

