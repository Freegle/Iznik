test('damlevlim gives the answer MySQL gave, for every input in the table', { skip }, () => {
  const out = column(cases.damlevlim.map((c) => `SELECT damlevlim(${lit(c.s1)}, ${lit(c.s2)}, ${c.n});`).join('\n'))
  assert.equal(out.length, cases.damlevlim.length)
  const bad = []
  cases.damlevlim.forEach((c, i) => {
    if (Number(out[i]) !== c.mysql) bad.push(`${c.name}: MySQL ${c.mysql}, PostgreSQL ${out[i]}`)
  })
  assert.deepEqual(bad, [])
})

test('damlevlim below the limit is the exact edit distance', { skip }, () => {
  // Below n there is no early exit, so the answer is levenshtein.
  const rows = cases.damlevlim.filter((c) => c.mysql < c.n && c.s1 && c.s2)
  assert.ok(rows.length > 40)
  const out = column(rows.map((c) => `SELECT levenshtein(unaccent(lower(${lit(c.s1)})), unaccent(lower(${lit(c.s2)})));`).join('\n'))
  rows.forEach((c, i) => assert.equal(Number(out[i]), c.mysql, c.name))
})

test('damlevlim does not fail on a long string whose letters unaccent expands', { skip }, () => {
  // unaccent turns one letter into two, so the cut to 255 characters has to come after it.
  const out = column(`SELECT damlevlim(repeat('ß', 200), 'x', 3);
    SELECT damlevlim('gmail.com', repeat('æ', 200) || 'x', 3);
    SELECT damlevlim(repeat('ß', 600), repeat('ß', 600), 3);`)
  assert.equal(out.length, 3)
  out.forEach((v) => assert.ok(Number.isInteger(Number(v)), v))
  assert.equal(Number(out[2]), 0)
})

test('the GET /domains query suggests what MySQL suggested', { skip }, () => {
  // The query as iznik-server-go/domain/domain.go builds it, bound the way pgx binds it.
  const bad = []
  for (const c of cases.domainSuggestions) {
    const out = psql(
      DB,
      `PREPARE s(text) AS SELECT domain FROM domains_common WHERE damlevlim(domain, $1, LENGTH($1)) < 3 ORDER BY count DESC LIMIT 5;
       EXECUTE s(${lit(c.input)});
       DEALLOCATE s;`,
    ).split('\n').filter(Boolean)
    if (JSON.stringify(out) !== JSON.stringify(c.suggestions)) bad.push(`${c.input}: MySQL ${c.suggestions.join(' ')}, PostgreSQL ${out.join(' ')}`)
  }
  assert.deepEqual(bad, [])
})

test('the call-site cases cover typed domains of every length that matters', { skip }, () => {
  const lens = new Set(cases.domainSuggestions.map((c) => Buffer.byteLength(c.input, 'utf8')))
  for (const n of [1, 2, 3, 4]) assert.ok(lens.has(n), `no typed domain of ${n} bytes`)
  assert.ok(cases.domainSuggestions.some((c) => c.suggestions.length === 0))
  assert.ok(cases.domainSuggestions.some((c) => c.suggestions.length === 5))
})

test('levenshtein_less_equal alone agrees with the call site when the typed domain has 3 bytes or more', { skip }, () => {
  // The query a dialect layer can use directly once the short inputs are decided: within 2 edits.
  const long = cases.domainSuggestions.filter((c) => Buffer.byteLength(c.input, 'utf8') >= 3)
  assert.ok(long.length > 20)
  for (const c of long) {
    const out = psql(
      DB,
      `SELECT domain FROM domains_common WHERE levenshtein_less_equal(unaccent(lower(domain::text)), unaccent(lower(${lit(c.input)})), 2) < 3 ORDER BY count DESC LIMIT 5;`,
    ).split('\n').filter(Boolean)
    assert.deepEqual(out, c.suggestions, c.input)
  }
})
