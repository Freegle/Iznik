test('generated columns are translated and VIRTUAL becomes STORED', () => {
  const { sql } = convert(
    dump(
      table('t', [
        idCol,
        '`a` varchar(32) DEFAULT NULL',
        '`b` datetime DEFAULT NULL',
        '`c` datetime DEFAULT NULL',
        '`h` varchar(32) COLLATE utf8mb4_unicode_ci GENERATED ALWAYS AS (md5(lower(`a`))) VIRTUAL',
        '`f` tinyint(1) GENERATED ALWAYS AS ((`b` > `c`)) STORED',
        "`v` varchar(255) COLLATE utf8mb4_unicode_ci GENERATED ALWAYS AS (if((`b` is null),`a`,NULL)) STORED",
        'PRIMARY KEY (`id`)',
      ])
    )
  )
  assert.match(sql, /h varchar\(32\) GENERATED ALWAYS AS \(md5\(lower\(a\)\)\) STORED/)
  assert.match(sql, /f smallint GENERATED ALWAYS AS \(\(\(b > c\)\)::int\) STORED/)
  assert.match(sql, /v varchar\(255\) GENERATED ALWAYS AS \(\(CASE WHEN \(b is null\) THEN a ELSE NULL END\)\) STORED/)
})

test('translateExpr handles introducers, escaped quotes and ifnull, and refuses unknown functions', () => {
  assert.equal(translateExpr("(`c` not in (_utf8mb4'It\\'s',_utf8mb4'x'))", 't.c'), "(c not in ('It''s','x'))")
  assert.equal(translateExpr('ifnull(`a`,`b`)', 't.c'), 'coalesce(a, b)')
  assert.throws(() => translateExpr('concat(`a`,`b`)', 't.c'), /concat\(\), which is not translated/)
})

test('an unknown column attribute stops the conversion', () => {
  assert.throws(() => parseColumn('`a` int FANCY NOT NULL'), /unrecognised column attribute/)
})

test('constructs that are not translated stop the conversion', () => {
  assert.throws(() => convert(dump(table('t', [idCol, 'PRIMARY KEY (`id`)', 'FULLTEXT KEY `f` (`id`)']))), /FULLTEXT/)
  assert.throws(() => convert(dump(table('t', [idCol, '`a` int ZEROFILL', 'PRIMARY KEY (`id`)']))), /ZEROFILL/)
  assert.throws(() => convert(dump(table('t', [idCol, 'PRIMARY KEY (`id`)'], ') ENGINE=InnoDB PARTITION BY HASH (id);'))), /table option/)
  assert.throws(() => convert(dump(table('t', [idCol, '`a` varchar(9) DEFAULT NULL', 'PRIMARY KEY (`id`)', 'UNIQUE KEY `u` (`a`(5))'])), { caseSensitive: { 't.*': 'x' } }), /uniqueness would change/)
  assert.throws(() => convert(dump(table('t', [idCol, '`a` int DEFAULT (rand())', 'PRIMARY KEY (`id`)']))), /unhandled expression default/)
  assert.throws(() => convert('nothing here'), /no tables/)
})

test('a text column in a unique key must be decided in the config', () => {
  const body = dump(table('t', [idCol, '`email` varchar(255) COLLATE utf8mb4_unicode_ci NOT NULL', 'PRIMARY KEY (`id`)', 'UNIQUE KEY `e` (`email`)']))
  assert.throws(() => convert(body, {}), /t\.email/)
  const ci = convert(body, { citext: ['t.email'] }).sql
  assert.match(ci, /email citext NOT NULL/)
  const cs = convert(body, { caseSensitive: { 't.*': 'a reason' } }).sql
  assert.match(cs, /email varchar\(255\) NOT NULL/)
})

