// Unit tests for the MySQL to PostgreSQL schema converter. No database needed.
import test from 'node:test'
import assert from 'node:assert/strict'
import { convert, parseColumn, translateExpr, qi, fit, ConvertError } from './convert.mjs'

const dump = (body) => `-- header\nDROP TABLE IF EXISTS \`t\`;\n${body}\n`

function table(name, lines, tail = ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;") {
  return `CREATE TABLE \`${name}\` (\n${lines.map((l) => '  ' + l).join(',\n')}\n${tail}`
}

const idCol = '`id` bigint unsigned NOT NULL AUTO_INCREMENT'

test('integer types and identity', () => {
  const { sql } = convert(
    dump(
      table('t', [
        idCol,
        "`a` tinyint(1) NOT NULL DEFAULT '1'",
        '`b` int unsigned DEFAULT NULL',
        '`c` smallint unsigned NOT NULL',
        '`d` mediumint NOT NULL',
        'PRIMARY KEY (`id`)',
      ])
    )
  )
  assert.match(sql, /id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL/)
  assert.match(sql, /a smallint DEFAULT 1 NOT NULL/)
  assert.match(sql, /b bigint,/)
  assert.match(sql, /c integer NOT NULL/)
  assert.match(sql, /d integer NOT NULL/)
  assert.match(sql, /PRIMARY KEY \(id\)/)
})

test('enum becomes text with a CHECK that allows the listed values', () => {
  const { sql } = convert(
    dump(table('t', [idCol, "`kind` enum('A','B''s','') COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'A'", 'PRIMARY KEY (`id`)']))
  )
  assert.match(sql, /kind text DEFAULT 'A' NOT NULL/)
  assert.match(sql, /CONSTRAINT t_kind_check CHECK \(kind IN \('A', 'B''s', ''\)\)/)
})

test('set becomes plain text', () => {
  const { sql } = convert(dump(table('t', [idCol, "`s` set('x','y') DEFAULT NULL", 'PRIMARY KEY (`id`)'])))
  assert.match(sql, /s text,/)
})

test('timestamp, datetime, json, blob and geometry types', () => {
  const { sql } = convert(
    dump(
      table('t', [
        idCol,
        '`ts` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP',
        '`ts3` timestamp(3) NULL DEFAULT NULL',
        '`dt` datetime DEFAULT NULL',
        '`j` json DEFAULT NULL',
        '`bl` longblob',
        '`g` geometry NOT NULL /*!80003 SRID 3857 */',
        '`p` point DEFAULT NULL',
        '`d` decimal(10,2) NOT NULL DEFAULT \'0.00\'',
        'PRIMARY KEY (`id`)',
      ])
    )
  )
  assert.match(sql, /ts timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL/)
  assert.match(sql, /ts3 timestamptz\(3\),/)
  assert.match(sql, /dt timestamp,/)
  assert.match(sql, /j jsonb,/)
  assert.match(sql, /bl bytea,/)
  assert.match(sql, /g geometry\(Geometry,4326\) NOT NULL/)
  assert.match(sql, /p geometry\(Point,4326\),/)
  assert.match(sql, /d numeric\(10,2\) DEFAULT 0\.00 NOT NULL/)
})

test('ON UPDATE CURRENT_TIMESTAMP becomes a trigger that skips an explicit change and ignores generated columns', () => {
  const { sql } = convert(
    dump(table('t', [idCol, '`ts` timestamp NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP', '`g` int GENERATED ALWAYS AS ((`id` + 1)) STORED', 'PRIMARY KEY (`id`)']))
  )
  assert.match(sql, /CREATE FUNCTION iznik_on_update_t\(\) RETURNS trigger/)
  assert.match(sql, /IF ROW\(NEW\.id, NEW\.ts\) IS DISTINCT FROM ROW\(OLD\.id, OLD\.ts\) THEN/)
  assert.match(sql, /IF NEW\.ts IS NOT DISTINCT FROM OLD\.ts THEN NEW\.ts := CURRENT_TIMESTAMP/)
  assert.match(sql, /CREATE TRIGGER t_on_update BEFORE UPDATE ON t FOR EACH ROW EXECUTE FUNCTION iznik_on_update_t\(\)/)
})

test('keys: unique and plain indexes are named after the table, prefixes are dropped, spatial is GiST', () => {
  const { sql, report } = convert(
    dump(
      table('t', [
        idCol,
        '`a` varchar(255) COLLATE utf8mb4_bin NOT NULL',
        '`b` varchar(1024) DEFAULT NULL',
        '`g` geometry NOT NULL /*!80003 SRID 3857 */',
        'PRIMARY KEY (`id`)',
        'UNIQUE KEY `a` (`a`)',
        'KEY `b` (`b`(768))',
        'KEY `idb` (`id`,`a` DESC)',
        'SPATIAL KEY `g` (`g`)',
      ])
    )
  )
  assert.match(sql, /CREATE UNIQUE INDEX t_a ON t \(a\);/)
  assert.match(sql, /CREATE INDEX t_b ON t \(b\);/)
  assert.match(sql, /CREATE INDEX t_idb ON t \(id, a DESC\);/)
  assert.match(sql, /CREATE INDEX t_g ON t USING gist \(g\);/)
  assert.match(sql, /a varchar\(255\) COLLATE "C" NOT NULL/)
  assert.ok(report.counts.has('key prefix length dropped'))
})

test('foreign keys come after every table and keep their actions', () => {
  const { sql } = convert(
    dump(
      table('child', [idCol, '`pid` bigint unsigned NOT NULL', 'PRIMARY KEY (`id`)', 'CONSTRAINT `child_fk` FOREIGN KEY (`pid`) REFERENCES `parent` (`id`) ON DELETE CASCADE']) +
        '\n' +
        table('parent', [idCol, 'PRIMARY KEY (`id`)'])
    )
  )
  const fk = sql.indexOf('ALTER TABLE child ADD CONSTRAINT child_fk FOREIGN KEY (pid) REFERENCES parent (id) ON DELETE CASCADE;')
  assert.ok(fk > sql.indexOf('CREATE TABLE parent'))
})

test('reserved words are quoted', () => {
  assert.equal(qi('order'), '"order"')
  assert.equal(qi('user'), '"user"')
  assert.equal(qi('timestamp'), 'timestamp')
  assert.equal(qi('yahooUserId'), '"yahooUserId"')
})

test('long generated names are cut, stable and unique', () => {
  const long = 'x'.repeat(70)
  assert.ok(fit(long).length <= 63)
  assert.equal(fit(long), fit(long))
  assert.notEqual(fit(long + 'a'), fit(long + 'b'))
  assert.throws(() => qi(long), ConvertError)
})

test('column comments and table comments become COMMENT ON', () => {
  const { sql } = convert(
    dump(table('t', [idCol, "`a` int DEFAULT NULL COMMENT 'it''s a number'", 'PRIMARY KEY (`id`)'], ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='About t';"))
  )
  assert.match(sql, /COMMENT ON TABLE t IS 'About t';/)
  assert.match(sql, /COMMENT ON COLUMN t\.a IS 'it''s a number';/)
})

test('zero-date default on a timestamp becomes the epoch', () => {
  const { sql } = convert(dump(table('t', [idCol, "`e` timestamp NOT NULL DEFAULT '0000-00-00 00:00:00'", 'PRIMARY KEY (`id`)'])))
  assert.match(sql, /e timestamptz DEFAULT '1970-01-01 00:00:00\+00' NOT NULL/)
})

test('generated columns are translated and VIRTUAL becomes STORED', () => {
  const { sql } = convert(
    dump(
      table('t', [
        idCol,
        '`a` varchar(32) DEFAULT NULL',
        '`b` datetime DEFAULT NULL',
        '`c` datetime DEFAULT NULL',
        '`h` varchar(32) COLLATE utf8mb4_unicode_ci GENERATED ALWAYS AS (md5(lower(`a`))) VIRTUAL',
        '`f` tinyint(1) GENERATED ALWAYS AS ((`b` > `c`)) STORED',
        "`v` varchar(255) COLLATE utf8mb4_unicode_ci GENERATED ALWAYS AS (if((`b` is null),`a`,NULL)) STORED",
        'PRIMARY KEY (`id`)',
      ])
    )
  )
  assert.match(sql, /h varchar\(32\) GENERATED ALWAYS AS \(md5\(lower\(a\)\)\) STORED/)
  assert.match(sql, /f smallint GENERATED ALWAYS AS \(\(\(b > c\)\)::int\) STORED/)
  assert.match(sql, /v varchar\(255\) GENERATED ALWAYS AS \(\(CASE WHEN \(b is null\) THEN a ELSE NULL END\)\) STORED/)
})

test('translateExpr handles introducers, escaped quotes and ifnull, and refuses unknown functions', () => {
  assert.equal(translateExpr("(`c` not in (_utf8mb4'It\\'s',_utf8mb4'x'))", 't.c'), "(c not in ('It''s','x'))")
  assert.equal(translateExpr('ifnull(`a`,`b`)', 't.c'), 'coalesce(a, b)')
  assert.throws(() => translateExpr('concat(`a`,`b`)', 't.c'), /concat\(\), which is not translated/)
})

test('an unknown column attribute stops the conversion', () => {
  assert.throws(() => parseColumn('`a` int FANCY NOT NULL'), /unrecognised column attribute/)
})

test('constructs that are not translated stop the conversion', () => {
  assert.throws(() => convert(dump(table('t', [idCol, 'PRIMARY KEY (`id`)', 'FULLTEXT KEY `f` (`id`)']))), /FULLTEXT/)
  assert.throws(() => convert(dump(table('t', [idCol, '`a` int ZEROFILL', 'PRIMARY KEY (`id`)']))), /ZEROFILL/)
  assert.throws(() => convert(dump(table('t', [idCol, 'PRIMARY KEY (`id`)'], ') ENGINE=InnoDB PARTITION BY HASH (id);'))), /table option/)
  assert.throws(() => convert(dump(table('t', [idCol, '`a` varchar(9) DEFAULT NULL', 'PRIMARY KEY (`id`)', 'UNIQUE KEY `u` (`a`(5))'])), { caseSensitive: { 't.*': 'x' } }), /uniqueness would change/)
  assert.throws(() => convert(dump(table('t', [idCol, '`a` int DEFAULT (rand())', 'PRIMARY KEY (`id`)']))), /unhandled expression default/)
  assert.throws(() => convert('nothing here'), /no tables/)
})

test('a text column in a unique key must be decided in the config', () => {
  const body = dump(table('t', [idCol, '`email` varchar(255) COLLATE utf8mb4_unicode_ci NOT NULL', 'PRIMARY KEY (`id`)', 'UNIQUE KEY `e` (`email`)']))
  assert.throws(() => convert(body, {}), /t\.email/)
  const ci = convert(body, { citext: ['t.email'] }).sql
  assert.match(ci, /email citext NOT NULL/)
  const cs = convert(body, { caseSensitive: { 't.*': 'a reason' } }).sql
  assert.match(cs, /email varchar\(255\) NOT NULL/)
})

test('a config entry that names a missing or non-text column is an error', () => {
  const body = dump(table('t', [idCol, '`n` int NOT NULL', 'PRIMARY KEY (`id`)']))
  assert.throws(() => convert(body, { citext: ['nope.x'] }), /no table nope/)
  assert.throws(() => convert(body, { citext: ['t.n'] }), /not a text column/)
})

test('a foreign key column follows a citext parent', () => {
  const body = dump(
    table('parent', [idCol, '`name` varchar(80) COLLATE utf8mb4_unicode_ci NOT NULL', 'PRIMARY KEY (`id`)', 'UNIQUE KEY `n` (`name`)']) +
      '\n' +
      table('child', [idCol, '`pname` varchar(80) COLLATE utf8mb4_unicode_ci DEFAULT NULL', 'PRIMARY KEY (`id`)', 'CONSTRAINT `c_fk` FOREIGN KEY (`pname`) REFERENCES `parent` (`name`)'])
  )
  const { sql } = convert(body, { citext: ['parent.name'] })
  assert.match(sql, /CREATE TABLE child \(\n {2}id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n {2}pname citext,/)
})

test('stored routines are skipped and named, triggers and views are not silently dropped', () => {
  const routines = "DELIMITER ;;\nCREATE DEFINER=`root`@`localhost` FUNCTION `f1`(a INT) RETURNS int\nBEGIN RETURN a; END ;;\nDELIMITER ;\n"
  const { report } = convert(dump(table('t', [idCol, 'PRIMARY KEY (`id`)'])) + routines)
  assert.ok(report.notes.some((n) => n.includes('f1')))
  assert.throws(() => convert(dump(table('t', [idCol, 'PRIMARY KEY (`id`)'])) + 'CREATE VIEW v AS SELECT 1;\n'), /views/)
})

test('the output is deterministic and lists the existing migrations as run', () => {
  const body = dump(table('migrations', [idCol, '`migration` varchar(255) NOT NULL', '`batch` int NOT NULL', 'PRIMARY KEY (`id`)']))
  const a = convert(body, {}, { migrations: ['2025_01_01_000000_a', '2025_01_02_000000_b'] }).sql
  const b = convert(body, {}, { migrations: ['2025_01_01_000000_a', '2025_01_02_000000_b'] }).sql
  assert.equal(a, b)
  assert.match(a, /INSERT INTO migrations \(migration, batch\) VALUES\n {2}\('2025_01_01_000000_a', 1\),\n {2}\('2025_01_02_000000_b', 1\);/)
})

test('every table in the committed baseline file loads from the same text the converter writes', async () => {
  // The baseline is generated. Its header says so, and it carries the extension and helper
  // function lines the converter always writes.
  const fs = await import('node:fs')
  const url = new URL('../../iznik-batch/database/postgres/baseline.sql', import.meta.url)
  const text = fs.readFileSync(url, 'utf8')
  assert.match(text, /^-- PostgreSQL baseline generated by tools\/pg-schema\/convert\.mjs/)
  assert.match(text, /CREATE EXTENSION IF NOT EXISTS postgis;/)
  assert.match(text, /CREATE FUNCTION iznik_reset_identities\(\)/)
  assert.ok((text.match(/^CREATE TABLE /gm) || []).length > 250)
  assert.ok(!/`/.test(text.replace(/COMMENT ON[^\n]*/g, '')), 'no MySQL backticks outside comments')
})

test('setup-test-database.sh builds PostgreSQL only when PG_ENGINE=1, after the MySQL path', async () => {
  const fs = await import('node:fs')
  const text = fs.readFileSync(new URL('../../scripts/setup-test-database.sh', import.meta.url), 'utf8')
  const mysqlEnd = text.indexOf('echo "iznik_go_test ready (schema cloned from migrated iznik)"')
  const guard = text.indexOf('if [ "${PG_ENGINE:-}" = "1" ]; then')
  assert.ok(mysqlEnd > 0 && guard > mysqlEnd, 'the PostgreSQL block comes after the MySQL path')
  assert.equal(text.split('setup-pg-database.sh').length - 1, 2, 'one comment and one call')
  // Nothing before the guard mentions PostgreSQL.
  assert.ok(!/postgres|PG_/i.test(text.slice(0, mysqlEnd)))
})
